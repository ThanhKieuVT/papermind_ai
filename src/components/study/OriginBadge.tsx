import type { StudyOrigin } from "@/lib/study/types";
import { Badge } from "@/components/ui/primitives";

export const ORIGIN_BADGE: Record<StudyOrigin, { label: string; tone: "violet" | "amber" | "neutral"; title: string }> = {
  ai: { label: "AI-generated", tone: "violet", title: "Generated by AI from excerpts of this paper" },
  "rule-based": { label: "Rule-based", tone: "amber", title: "Extracted by simple text patterns (no AI)" },
  manual: { label: "Manual", tone: "neutral", title: "Created by you" },
};

export function OriginBadge({ origin, page }: { origin: StudyOrigin; page?: number | null }) {
  const b = ORIGIN_BADGE[origin];
  return (
    <span className="inline-flex gap-1">
      <Badge tone={b.tone} title={b.title}>{b.label}</Badge>
      {page ? <Badge>p. {page}</Badge> : null}
    </span>
  );
}
